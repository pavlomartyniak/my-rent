/** Рядок про сторону: повні дані, якщо вони є в договорі (версія 3), інакше ім'я й телефон */
function partyLine(role: string, p: ContractParty): string {
  const phone = p.phone ? `, тел. ${p.phone}` : '';
  const l = p.legal;
  if (!l) return `${role}: ${p.name}${phone}.`;
  const license = l.license ? `, посвідчення водія серії ${l.license.series} № ${l.license.number}, категорії ${l.license.categories.join(', ')}` : '';
  return `${role}: ${p.name}, ${partyTypeLabel(l)}, РНОКПП ${l.rnokpp}, ${idDocLabel(l.idDoc)}, адреса: ${l.address}${license}${phone}.`;
}

