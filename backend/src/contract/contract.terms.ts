const ONES_M = ['', 'один', 'два', 'три', 'чотири', 'п’ять', 'шість', 'сім', 'вісім', 'дев’ять'];
const ONES_F = ['', 'одна', 'дві', 'три', 'чотири', 'п’ять', 'шість', 'сім', 'вісім', 'дев’ять'];
const TEENS = ['десять', 'одинадцять', 'дванадцять', 'тринадцять', 'чотирнадцять', 'п’ятнадцять', 'шістнадцять', 'сімнадцять', 'вісімнадцять', 'дев’ятнадцять'];
const TENS = ['', '', 'двадцять', 'тридцять', 'сорок', 'п’ятдесят', 'шістдесят', 'сімдесят', 'вісімдесят', 'дев’яносто'];
const HUNDREDS = ['', 'сто', 'двісті', 'триста', 'чотириста', 'п’ятсот', 'шістсот', 'сімсот', 'вісімсот', 'дев’ятсот'];
const form = (n: number, one: string, few: string, many: string) => (n % 100 >= 11 && n % 100 <= 14 ? many : n % 10 === 1 ? one : n % 10 >= 2 && n % 10 <= 4 ? few : many);

function triple(n: number, feminine: boolean): string {
  const ones = feminine ? ONES_F : ONES_M;
  const h = Math.floor(n / 100);
  const rest = n % 100;
  const parts = [HUNDREDS[h]];
  if (rest >= 10 && rest < 20) parts.push(TEENS[rest - 10]!);
  else parts.push(TENS[Math.floor(rest / 10)]!, ones[rest % 10]!);
  return parts.filter(Boolean).join(' ');
}

/** Сума гривнями словами: 12000 → «дванадцять тисяч гривень» (до мільярда) */
export function uahWords(amount: number): string {
  const n = Math.round(amount);
  if (n <= 0) return 'нуль гривень';
  const millions = Math.floor(n / 1_000_000);
  const thousands = Math.floor(n / 1000) % 1000;
  const units = n % 1000;
  const out: string[] = [];
  if (millions) out.push(triple(millions, false), form(millions, 'мільйон', 'мільйони', 'мільйонів'));
  if (thousands) out.push(triple(thousands, true), form(thousands, 'тисяча', 'тисячі', 'тисяч'));
  if (units) out.push(triple(units, true));
  out.push(form(n, 'гривня', 'гривні', 'гривень'));
  return out.filter(Boolean).join(' ');
}

