/** Рядок про сторону для редакції 4: повні дані й статус; без юридичних даних — лише ім'я й телефон */
function partyLineV4(role: string, p: ContractParty, extra = ''): string {
  const phone = p.phone ? `, тел. ${p.phone}` : '';
  const l = p.legal;
  if (!l) return `${role}: ${p.name}${phone}.`;
  const fop = l.partyType === 'fop' ? `, зареєстрований як ФОП, КВЕД ${l.kved ?? ''}` : '';
  return `${role}: ${p.name}, РНОКПП ${l.rnokpp}, документ про особу: ${idDocLabel(l.idDoc)}, адреса: ${l.address}${phone}${extra}${fop}.`;
}

